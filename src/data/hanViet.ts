const HAN_RE = /[\u4e00-\u9fff]/;

/** Ghép âm Hán-Việt từng chữ, cách nhau bởi dấu cách. Chữ không có bảng → '·'. */
export function hanVietOf(text: string): string {
  const parts: string[] = [];
  for (const ch of text) {
    if (!HAN_RE.test(ch)) continue;
    parts.push(HAN_VIET[ch] ?? '\u00b7');
  }
  return parts.join(' ');
}
